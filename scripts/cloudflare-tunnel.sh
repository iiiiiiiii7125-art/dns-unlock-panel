#!/usr/bin/env bash
# 可选入口: Cloudflare Tunnel (cloudflared) — 把面板暴露到公网域名, 不改面板本身。
# 面板仍跑在任意 VPS 上 (单二进制 + 本地文件); Tunnel 只是入口, 不是必需品。
# 前置: 已在 Cloudflare 注册域名, 并安装 cloudflared。
# 用法: PANEL_DOMAIN=panel.example.com ./scripts/cloudflare-tunnel.sh
set -euo pipefail
DOMAIN="${PANEL_DOMAIN:-}"
[ -n "$DOMAIN" ] || { echo "用法: PANEL_DOMAIN=panel.example.com $0"; exit 1; }
command -v cloudflared >/dev/null || { echo "请先安装 cloudflared"; exit 1; }
command -v python3 >/dev/null || { echo "需要 python3（解析 tunnel 凭据）"; exit 1; }
[ "$(id -u)" = "0" ] || { echo "请用 root 运行"; exit 1; }
NAME="dnsunlock-panel"
echo "== 1/4 登录 Cloudflare (只需一次) =="
cloudflared tunnel login
echo "== 2/4 创建 tunnel =="
if ! cloudflared tunnel list 2>/dev/null | grep -q "$NAME"; then
  cloudflared tunnel create "$NAME"
fi
echo "== 3/4 配置 ingress (localhost:8080) =="
# 凭据文件: 扫描 ~/.cloudflared/*.json，按文件内的 TunnelName 匹配（不用 awk 抠表格）。
CRED=$(python3 - "$NAME" <<'PYEOF'
import glob, json, sys
for f in glob.glob("/root/.cloudflared/*.json"):
    try:
        d = json.load(open(f))
    except Exception:
        continue
    if d.get("TunnelName") == sys.argv[1]:
        print(f); break
else:
    sys.exit("找不到 tunnel 凭据文件，请确认 cloudflared tunnel create 已成功")
PYEOF
)
echo "== 3/4 配置 ingress (localhost:8080) =="
# Q-01: 写配置前先看有没有用户自有的 /etc/cloudflared/config.yml。
# 已有自有配置时默认停下（直接覆盖会当场丢掉用户原有的隧道配置，
# 找不回来）；只有用户明确设 CLOUDFLARED_OVERWRITE_EXISTING=1 时才
# 先备份再覆盖，备份路径记进标记，卸载时原样恢复。
CONFIG_FILE="/etc/cloudflared/config.yml"
MARKER_DIR="/etc/dnsunlock"
MARKER="$MARKER_DIR/cloudflared-by-dnsunlock"
CONFIG_STATE="created"
CONFIG_BACKUP=""
if [ -f "$CONFIG_FILE" ]; then
  if grep -q "Generated by dnsunlock cloudflare-tunnel.sh" "$CONFIG_FILE" 2>/dev/null; then
    CONFIG_STATE="ours"
    echo "已有本面板生成的 config.yml，本次直接重写。"
  elif [ "${CLOUDFLARED_OVERWRITE_EXISTING:-}" = "1" ]; then
    CONFIG_BACKUP="$CONFIG_FILE.bak.$(date +%Y%m%d-%H%M%S)"
    cp -a "$CONFIG_FILE" "$CONFIG_BACKUP" || { echo "备份已有 config.yml 失败，停止"; exit 1; }
    CONFIG_STATE="overwritten"
    echo "已备份原有 config.yml 到 $CONFIG_BACKUP，卸载时会原样恢复。"
  else
    echo "停止：$CONFIG_FILE 已存在且不是本面板生成的（疑似你自己的 cloudflared 隧道配置）。"
    echo "直接覆盖会丢掉你原有的隧道配置。请先手动备份/移走它，或确认要覆盖时再跑："
    echo "  CLOUDFLARED_OVERWRITE_EXISTING=1 PANEL_DOMAIN=$DOMAIN $0"
    echo "（覆盖前脚本会自动把原文件备份到 config.yml.bak.<时间>，卸载时恢复。）"
    exit 1
  fi
fi
mkdir -p /etc/cloudflared
cat > "$CONFIG_FILE" <<EOF
# Generated by dnsunlock cloudflare-tunnel.sh (panel ingress to 127.0.0.1:8080)
tunnel: $NAME
credentials-file: $CRED
ingress:
  - hostname: $DOMAIN
    service: http://127.0.0.1:8080
  - service: http_status:404
EOF
echo "== 4/4 DNS 记录 + 启动 =="
cloudflared tunnel route dns "$NAME" "$DOMAIN"
# Q-01: 已有 cloudflared 服务时不重装服务（那可能是用户自己的隧道在用），
# 只重启让新配置生效；卸载时也只拆本脚本装的服务。
# 注意：先看旧标记——本面板之前装的服务（旧标记 service=created）重跑时
# 仍算我们的，不能因为“服务文件已存在”就改记成 preexisting，否则卸载
# 时不会拆它，留下一个指向已删配置的孤儿服务。
SERVICE_STATE="created"
if [ -f "$MARKER" ] && grep -q '^service=created$' "$MARKER" 2>/dev/null; then
  echo "cloudflared 服务是本面板之前装的，本次不重装，只重启它以加载新配置。"
  systemctl restart cloudflared
elif [ -f /etc/systemd/system/cloudflared.service ] || [ -f /usr/lib/systemd/system/cloudflared.service ] || [ -f /lib/systemd/system/cloudflared.service ]; then
  SERVICE_STATE="preexisting"
  echo "检测到已有的 cloudflared 服务（疑似你自己的隧道在用），本次不重装服务，只重启它以加载新配置；卸载 dnsunlock 时不会拆它。"
  systemctl restart cloudflared
else
  cloudflared service install
  systemctl enable --now cloudflared
fi
# Q-01/M-04: 留安装标记（key=value，卸载脚本按标记只清本面板的东西）：
# config=created（本脚本新建）/ours（已是本面板生成的）/overwritten
#   （覆盖了用户自有配置，backup=备份路径，卸载时恢复）
# service=created（本脚本装的服务）/preexisting（用户自有的服务，别碰）
mkdir -p "$MARKER_DIR"
printf 'config=%s\nbackup=%s\nservice=%s\n' "$CONFIG_STATE" "$CONFIG_BACKUP" "$SERVICE_STATE" > "$MARKER"
echo
echo "完成: https://$DOMAIN  -> 本机面板 :8080"
echo "务必在 Cloudflare 控制台加 Cache Rule (见 README 第 6 节):"
echo "  /api/* 、/install.sh 、/dl/* 全部 Bypass cache, 否则 DNS agent 轮询会被缓存。"
echo "  API 本身已返回 Cache-Control: no-store, Cache Rule 是第二层保险。"
echo "验证: curl -s https://$DOMAIN/api/v1/status | head -c 200"
