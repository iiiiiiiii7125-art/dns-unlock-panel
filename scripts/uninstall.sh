#!/usr/bin/env bash
# dnsunlock 卸载脚本。
# 顺序: 先还原被接管的系统 DNS（还原失败立即停，不删任何备份），再删服务/二进制/防火墙/Caddy。
# 面板数据默认保留；加 --purge 才删面板数据与配置。
set -euo pipefail
[ "$(id -u)" = "0" ] || { echo "请用 root 运行"; exit 1; }
PURGE=0
[ "${1:-}" = "--purge" ] && PURGE=1
# 1. 还原系统 DNS（如果安装时接管过）。还原失败 -> 停下，不删备份。
if [ -e /etc/dnsunlock/resolv.conf.orig ]; then
  echo "还原系统 DNS..."
  if [ -x /usr/local/bin/dnsunlock-restore-dns ]; then
    # v0.1.6：还原脚本默认要交互选备份；卸载是非交互流程，加 --yes
    #（默认还原最早的一份 = 原始状态，还原前仍自动备份当前状态）。
    /usr/local/bin/dnsunlock-restore-dns --yes || { echo "还原失败，已保留 /etc/dnsunlock/ 下的全部备份，请手动处理"; exit 1; }
  elif [ -f "$(dirname "$0")/restore-resolv.sh" ]; then
    bash "$(dirname "$0")/restore-resolv.sh" --yes || { echo "还原失败，已保留 /etc/dnsunlock/ 下的全部备份，请手动处理"; exit 1; }
  else
    echo "找不到还原脚本且存在原备份，停下不删：请手动用 /etc/dnsunlock/resolv.conf.orig 还原 /etc/resolv.conf"; exit 1
  fi
fi
# 2. 停服务、删 unit。
systemctl disable --now dnsunlock-agent dnsunlock-proxy dnsunlock-panel 2>/dev/null || true
rm -f /etc/systemd/system/dnsunlock-agent.service /etc/systemd/system/dnsunlock-proxy.service /etc/systemd/system/dnsunlock-panel.service
systemctl daemon-reload
# 3. 防火墙：安装流程本身从不自动放行 53（N-09），所以卸载时不删任何
# 防火墙规则——ufw/firewall-cmd 里现有的 53 规则是用户自己的，删了会拆
# 掉用户原有的 DNS 服务。只清理 dnsunlock 自己装过的东西（见下）。
# （旧版这里删防火墙 53 规则，已去掉。）
# 3b. cloudflared：只清 dnsunlock 自己装过的（M-04/Q-01）。
# cloudflare-tunnel.sh 装 tunnel 时会留 /etc/dnsunlock/cloudflared-by-dnsunlock
# 标记（key=value：config=created/ours/overwritten + backup 备份路径，
# service=created/preexisting）。没有标记 = 用户自己为别的隧道装的
# cloudflared，卸载时一律不动。卸载只删本面板新建的 config.yml；覆盖
# 过用户自有配置的，从备份恢复；目录只在删完本面板文件变空后才 rmdir，
# 绝不 rm -rf 整个 /etc/cloudflared。
MARKER="/etc/dnsunlock/cloudflared-by-dnsunlock"
if [ -f "$MARKER" ]; then
  CF_CONFIG="unknown"; CF_BACKUP=""; CF_SERVICE="created"
  if grep -q '^config=' "$MARKER" 2>/dev/null; then
    CF_CONFIG="$(grep '^config=' "$MARKER" | cut -d= -f2-)"
    CF_BACKUP="$(grep '^backup=' "$MARKER" | cut -d= -f2- || true)"
    CF_SERVICE="$(grep '^service=' "$MARKER" | cut -d= -f2- || true)"
  fi
  # 服务：只有本脚本装的才拆；用户自有的服务不动（Q-01）。
  if [ "$CF_SERVICE" = "preexisting" ]; then
    echo "cloudflared 服务是用户自有的（tunnel 脚本装 tunnel 时已存在），本次卸载不碰它。"
  else
    if command -v cloudflared >/dev/null 2>&1; then cloudflared service uninstall 2>/dev/null || true; fi
    systemctl disable --now cloudflared 2>/dev/null || true
    rm -f /etc/systemd/system/cloudflared.service
    systemctl daemon-reload
  fi
  # 配置：本面板新建/重写的才删；覆盖过用户自有配置的，从备份恢复。
  case "$CF_CONFIG" in
    created|ours)
      rm -f /etc/cloudflared/config.yml
      echo "已删除本面板生成的 /etc/cloudflared/config.yml。"
      ;;
    overwritten)
      if [ -n "$CF_BACKUP" ] && [ -f "$CF_BACKUP" ]; then
        mv "$CF_BACKUP" /etc/cloudflared/config.yml
        echo "已把你原有的 cloudflared 配置从备份恢复：$CF_BACKUP -> /etc/cloudflared/config.yml。"
      else
        echo "警告：tunnel 脚本曾覆盖过你原有的 cloudflared 配置，但备份 $CF_BACKUP 找不到了；本次不动 /etc/cloudflared/config.yml，请手动检查。"
      fi
      ;;
    *)
      # 旧版标记（空文件，分不清来源）：只在文件确实是本面板生成时才删。
      if grep -q "Generated by dnsunlock cloudflare-tunnel.sh" /etc/cloudflared/config.yml 2>/dev/null; then
        rm -f /etc/cloudflared/config.yml
        echo "已删除本面板生成的 /etc/cloudflared/config.yml（旧版标记）。"
      else
        echo "cloudflared 配置疑似用户自有（旧版标记，分不清来源），本次卸载不碰它。"
      fi
      ;;
  esac
  # 目录：只有空了才删，绝不 rm -rf 整个目录（Q-01）。
  if [ -d /etc/cloudflared ]; then
    rmdir /etc/cloudflared 2>/dev/null || echo "/etc/cloudflared 里还有别的文件，本次不删目录。"
  fi
elif [ -f /etc/systemd/system/cloudflared.service ] || [ -f /usr/lib/systemd/system/cloudflared.service ]; then
  echo "cloudflared 服务存在，但没有 dnsunlock 的安装标记，疑似用户自有配置，本次卸载不碰它。"
fi
# 4. Caddy 反代（仅删 dnsunlock 生成的那份），并去掉 install-panel.sh
# 追加的那行 import（P1-15 残留：以前只删文件，import 行留下来了）。
rm -f /etc/caddy/Caddyfile.d/dnsunlock
if [ -f /etc/caddy/Caddyfile ] && ! ls /etc/caddy/Caddyfile.d/* >/dev/null 2>&1; then
  sed -i '/^import Caddyfile\.d\/\*$/d' /etc/caddy/Caddyfile
fi
systemctl reload caddy 2>/dev/null || true
# 5. 二进制与配置。面板数据默认保留（--purge 才删）。
rm -f /usr/local/bin/dnsunlock /usr/local/bin/dnsunlock-restore-dns
rm -rf /etc/dnsunlock
if [ "$PURGE" = "1" ]; then
  rm -rf /var/lib/dnsunlock
  echo "已卸载 dnsunlock（含面板数据 --purge）。"
else
  echo "已卸载 dnsunlock（面板数据保留在 /var/lib/dnsunlock/panel.json，如需清掉请加 --purge 重跑）。"
fi
